def build_live_scenario() -> dict[str, Any]:
    """Build the Live Azure scenario from the current, user-editable orders."""
    orders: list[dict[str, Any]] = []
    for row in st.session_state.live_orders:
        order_id = str(row.get("order_id") or "").strip()
        if not order_id:
            continue
        substitute = row.get("substitute_sku")
        if isinstance(substitute, str):
            substitute = substitute.strip().upper()
        if not substitute or substitute == "NONE":
            substitute = None
        orders.append(
            {
                "order_id": order_id,
                "sku": str(row.get("sku") or "A").strip().upper(),
                "quantity": max(1, int(row.get("quantity") or 1)),
                "priority": max(1, int(row.get("priority") or 1)),
                "deadline_hours": max(1, int(row.get("deadline_hours") or 24)),
                "substitute_sku": substitute,
                "margin": max(0, int(row.get("margin") or 0)),
            }
        )
    return {**LIVE_SCENARIO_BASE, "orders": orders, "expedite_budget": max(0, int(st.session_state.live_expedite_budget))}


def run_model(model_name: str, replay: bool = False) -> None:
    if replay:
        record = VERIFIED_RESULTS[model_name]
        st.session_state.results[model_name] = {
            **record,
            "result": score_plan(record["plan"], SCENARIO),
            "scenario": SCENARIO,
            "source": "Recorded verified run · replayed locally",
        }
        return

    config = MODEL_OPTIONS[model_name]
    if not os.environ.get("AZURE_AI_PROJECT_ENDPOINT"):
        raise RuntimeError("AZURE_AI_PROJECT_ENDPOINT is not configured in model_comparison_app/.env")
    scenario = build_live_scenario()
    started = time.perf_counter()
    plan, usage = request_agent_plan(
        create_project_client(),
        config["agent_name"],
        config["agent_version"],
        scenario,
        extra_instructions=st.session_state.extra_instructions.get(model_name) or None,
    )
    st.session_state.results[model_name] = {
        "plan": plan,
        "result": score_plan(plan, scenario),
        "scenario": scenario,
        "usage": usage,
        "seconds": time.perf_counter() - started,
        "source": "Current live run",
    }


