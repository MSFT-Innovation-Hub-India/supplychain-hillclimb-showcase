def audit_plan(plan: dict[str, Any] | None, scenario: dict[str, Any]) -> dict[str, Any]:
    if not isinstance(plan, dict) or not isinstance(plan.get("decisions"), list):
        return {"issues": ["The model did not return a valid decisions list."], "decision_rows": []}

    orders = {order["order_id"]: order for order in scenario["orders"]}
    warehouses = {warehouse["warehouse_id"]: warehouse for warehouse in scenario["warehouses"]}
    inventory_used: dict[tuple[str, str], int] = defaultdict(int)
    capacity_used: dict[str, int] = defaultdict(int)
    expedite_spend = 0
    issues: list[str] = []
    rows = []

    for decision in plan["decisions"]:
        order = orders.get(decision.get("order_id"))
        if not order:
            issues.append(f"Unknown order {decision.get('order_id')} was returned.")
            continue
        if decision.get("action") == "defer":
            rows.append({"Order": order["order_id"], "Decision": "Defer", "Route": "-", "SKU": "-", "Qty": "-", "Delivery": "No shipment", "Cost": "$0"})
            continue
        warehouse = warehouses.get(decision.get("warehouse_id"))
        if not warehouse:
            issues.append(f"{order['order_id']} uses an unknown warehouse.")
            continue
        quantity = decision.get("quantity", 0)
        sku = decision.get("sku", "")
        mode = decision.get("shipping_mode", "")
        hours = warehouse.get(f"{mode}_hours", 0)
        unit_cost = warehouse.get(f"{mode}_cost", 0)
        cost = unit_cost * quantity
        on_time = hours <= order["deadline_hours"]
        inventory_used[(warehouse["warehouse_id"], sku)] += quantity
        capacity_used[warehouse["warehouse_id"]] += quantity
        if mode == "expedite":
            expedite_spend += cost
        rows.append(
            {
                "Order": order["order_id"],
                "Decision": mode.title(),
                "Route": warehouse["warehouse_id"],
                "SKU": sku + (" (substitute)" if sku != order["sku"] else ""),
                "Qty": quantity,
                "Delivery": f"{hours} h · {'On time' if on_time else 'Late'}",
                "Cost": f"${cost}",
            }
        )

    for (warehouse_id, sku), used in inventory_used.items():
        available = warehouses[warehouse_id]["inventory"].get(sku, 0)
        if used > available:
            issues.append(f"{warehouse_id} allocates {used} units of {sku}, but only {available} are available.")
    for warehouse_id, used in capacity_used.items():
        available = warehouses[warehouse_id]["shipment_capacity"]
        if used > available:
            issues.append(f"{warehouse_id} uses {used} units of capacity, above its limit of {available}.")
    if expedite_spend > scenario["expedite_budget"]:
        issues.append(f"Expedite spend is ${expedite_spend}, above the ${scenario['expedite_budget']} budget.")

    return {
        "issues": issues,
        "decision_rows": rows,
        "capacity_used": dict(capacity_used),
        "expedite_spend": expedite_spend,
    }


def rationale_for(model_name: str, record: dict[str, Any]) -> list[str]:
    result = record["result"]
    scenario = record["scenario"]
    audit = audit_plan(record["plan"], scenario)
    if not result["feasible"]:
        return [
            "The plan fails the operational gate, so the complete allocation receives zero reward.",
            *audit["issues"],
            "The failure is not about style: downstream execution would attempt inventory or capacity that does not exist.",
        ]

    metrics = result["metrics"]
    decisions = record["plan"].get("decisions", []) if isinstance(record["plan"], dict) else []
    expedited = [d.get("order_id") for d in decisions if isinstance(d, dict) and d.get("shipping_mode") == "expedite"]
    deferred = [d.get("order_id") for d in decisions if isinstance(d, dict) and d.get("action") == "defer"]
    rationale = [
        f"{len(scenario['orders'])} orders are covered by a feasible plan; priority-weighted on-time service is {metrics['service']:.1%}.",
        f"The plan retains {metrics['margin']:.1%} of available margin while spending \\${metrics['shipping_cost']:.0f} on shipping.",
        f"Expedite spend is \\${metrics['expedite_spend']:.0f} of the \\${scenario['expedite_budget']} budget.",
    ]
    if metrics["expedite_spend"] == 0:
        rationale.append("Every shipped order meets its deadline using standard service only, so no expedite budget is spent.")
    else:
        order_list = ", ".join(expedited) if expedited else "at least one order"
        rationale.append(f"Meeting every deadline required expediting {order_list}, which consumes part of the expedite budget.")
    if deferred:
        rationale.append(f"{len(deferred)} order(s) were deferred: {', '.join(deferred)}.")
    rationale.append("This explanation is computed from the returned plan and grader metrics; it is not hidden model chain-of-thought.")
    return rationale


